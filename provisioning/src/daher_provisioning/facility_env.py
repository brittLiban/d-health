"""Render and write a facility's `.env` file.

This is the handover point between provisioning and the clinical stack: everything the
stack needs to boot, written once, mode 0600.

Two safety properties matter more than the rendering itself:

1. **It refuses to overwrite an existing env file.** A facility's databases are
   initialised with the credentials from their first boot. Rewriting the file with fresh
   secrets does not rotate anything — it leaves a running stack whose passwords no longer
   match its own databases, and whose `OMRS_ADMIN_PASSWORD` is now a value that was only
   ever applied on first boot. Rotation is a separate, deliberate operation.
2. **It never logs a value.** Rendering returns a string that is written directly to a
   restricted file; nothing here prints, and the caller is expected to keep it that way.
"""

from __future__ import annotations

import os
import tempfile
from dataclasses import dataclass
from pathlib import Path

from daher_provisioning.models import Facility
from daher_provisioning.secrets import FacilitySecrets

